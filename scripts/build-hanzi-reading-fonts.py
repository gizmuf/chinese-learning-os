"""Subset the pinned Noto SC originals for Chinese OS. Requires fonttools[woff]."""
import argparse
import gzip
import hashlib
import json
import unicodedata
from io import BytesIO
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / 'public/fonts'
SOURCES = {
    'Screen': ('Sans', '2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b'),
    'Book': ('Serif', '2a2eae2628df83556c54018c41e20fa532c1b862c5256ae8b3f23feb918d12ca'),
}
BRUSH_MANIFESTS = ('hanzi-display-aed7c7982572.json', 'hanzi-display-hsk-07f2969cc9a4.json')
SAMPLE = '好玩儿'


def ideographs(text):
    return {ord(ch) for ch in text if unicodedata.name(ch, '').startswith('CJK UNIFIED IDEOGRAPH-')}


def study_characters():
    result = set()
    for directory in ('app', 'data'):
        for path in (ROOT / directory).rglob('*'):
            relative = path.relative_to(ROOT)
            if path.suffix not in {'.ts', '.tsx', '.json', '.tsv'} or 'sources' in relative.parts:
                continue
            if path.name.startswith('simplified-dictionary-policy') or path.name.endswith('-packed.ts'):
                continue
            result.update(ideographs(path.read_text(encoding='utf-8')))
    return result


def make_face(original, characters, name):
    family = 'Chinese OS ' + name
    stem = 'ChineseOS' + name.replace(' ', '')
    with TTFont(original, recalcTimestamp=False) as font:
        sub = subset.Subsetter()
        sub.populate(unicodes=characters)
        sub.subset(font)
        for tag, value in ((1, family), (3, stem), (4, family), (6, stem), (16, family)):
            for record in list(font['name'].names):
                if record.nameID == tag:
                    font['name'].setName(value, tag, record.platformID, record.platEncID, record.langID)
        cff = font['CFF '].cff
        cff.fontNames = [stem]
        cff.topDictIndex[0].FullName = family
        cff.topDictIndex[0].FamilyName = family
        font.flavor = 'woff2'
        buffer = BytesIO()
        font.save(buffer)
    binary = buffer.getvalue()
    digest = hashlib.sha256(binary).hexdigest()
    filename = f'{stem}-{digest[:12]}.woff2'
    (FONT_DIR / filename).write_bytes(binary)
    face = f"""@font-face {{
  font-family: '{family}';
  src: url('/fonts/{filename}') format('woff2');
  font-display: swap;
  font-weight: 400;
}}
"""
    return face, {'file': filename, 'sha256': digest, 'glyphs': len(characters)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('sans', type=Path, help='NotoSansCJKsc-Regular.otf')
    parser.add_argument('serif', type=Path, help='NotoSerifCJKsc-Regular.otf')
    args = parser.parse_args()
    with gzip.open(ROOT / 'public/dictionary/hsk-levels-2025.json.gz', 'rt') as asset:
        syllabus = json.load(asset)
    recognition = ideographs(''.join(syllabus['characters'].values()))
    vocabulary = ideographs(''.join(syllabus['words'].values()))
    brush = set()
    for name in BRUSH_MANIFESTS:
        brush.update(ideographs(json.loads((FONT_DIR / name).read_text())['characters']))
    required = recognition | vocabulary | brush
    candidates = study_characters() | required
    chars = candidates.copy()
    for original, (_, digest) in zip((args.sans, args.serif), SOURCES.values()):
        if hashlib.sha256(original.read_bytes()).hexdigest() != digest:
            raise ValueError(f'Wrong source font revision: {original}')
        with TTFont(original) as font:
            chars.intersection_update(font.getBestCmap())
    missing = required - chars
    if missing:
        raise ValueError('Missing required characters: ' + ''.join(map(chr, sorted(missing))))
    manifest = {
        'recognitionGlyphs': len(recognition),
        'brushGlyphs': len(brush),
        'glyphs': ''.join(map(chr, sorted(chars))),
        'authoredIdeographsOutsideNoto': ''.join(map(chr, sorted(candidates - chars))),
        'faces': {},
    }
    css = ['/* Generated by scripts/build-hanzi-reading-fonts.py. */\n']
    for (name, (collection, digest)), original in zip(SOURCES.items(), (args.sans, args.serif)):
        css_rule, face = make_face(original, chars, name)
        sample_rule, sample_face = make_face(original, set(map(ord, SAMPLE)), name + ' Preview')
        css.extend((css_rule, sample_rule))
        manifest['faces'][name] = {**face, 'preview': sample_face, 'sourceSHA256': digest,
                                    'license': f'/fonts/Noto-CJK-{collection}-OFL.txt',
                                    'source': f'https://github.com/notofonts/noto-cjk/blob/main/{collection}/OTF/SimplifiedChinese/{original.name}'}
    (ROOT / 'app/hanzi-reading-fonts.css').write_text('\n'.join(css))
    (FONT_DIR / 'hanzi-reading-fonts.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    print(f'{len(chars)} reading glyphs ({len(recognition)} recognition), {len(candidates - chars)} extra code points outside the Noto pair')


if __name__ == '__main__':
    main()
