export function termBase(term: Term) {
  return term.baseId
    ? items.find((i) => i.id === term.baseId)
    : items.find((i) => i.hanzi === term.hanzi);
}
export function termItem(term: Term, locale: Locale): Item {
  const base = termBase(term);
  if (base)
    return { ...localizeItem(base, locale), english: term.meaning[locale] };
  const example = sentences.find((s) => s.hanzi.includes(term.hanzi));
  return {
    id: "course03-" + term.id,
    lesson: course.lessonId,
    hanzi: term.hanzi,
    pinyin: term.pinyin,
    english: term.meaning[locale],
    sentence: example?.hanzi ?? term.hanzi,
    sentencePinyin: example?.pinyin ?? term.pinyin,
    translation: example?.meaning[locale] ?? term.meaning[locale],
  };
}
export function sentenceItem(s: Sentence, locale: Locale): Item {
  return {
    id: "course03-" + s.id,
    lesson: course.lessonId,
    hanzi: s.hanzi,
    pinyin: s.pinyin,
    english: s.meaning[locale],
    sentence: s.hanzi,
    sentencePinyin: s.pinyin,
    translation: s.meaning[locale],
  };
}
